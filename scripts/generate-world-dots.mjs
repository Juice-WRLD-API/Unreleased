// Rasterizes Natural Earth land (via world-atlas) into the compact dot grid
// that CdnWorldMap draws, and writes src/renderer/src/lib/worldDots.ts.
//
//   npm i --no-save world-atlas@2 topojson-client@3
//   node scripts/generate-world-dots.mjs
//
// Only needs re-running to change the grid step or latitude crop.
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'

const STEP = 2          // degrees per cell
const LAT_TOP = 84      // crop: nothing useful above/below these
const LAT_BOTTOM = -58

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-110m.json', 'utf8'))
const land = feature(topo, topo.objects.land)
const polys = []
for (const f of land.features ?? [land]) {
  const g = f.geometry
  if (g.type === 'Polygon') polys.push(g.coordinates)
  else if (g.type === 'MultiPolygon') polys.push(...g.coordinates)
}

function inRing(x, y, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j]
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}
// Even-odd across a polygon's rings so lakes/inland seas stay holes.
const onLand = (x, y) => polys.some((rings) => rings.reduce((n, r) => n + (inRing(x, y, r) ? 1 : 0), 0) % 2 === 1)

const cols = 360 / STEP
const rows = []
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  let bits = ''
  for (let c = 0; c < cols; c++) bits += onLand(-180 + (c + 0.5) * STEP, lat) ? '1' : '0'
  // Pack to hex, 4 cells per char.
  let hex = ''
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, '0'), 2).toString(16)
  rows.push(hex)
}

const out = `// GENERATED by scripts/generate-world-dots.mjs - do not edit by hand.
// Land mask on a ${STEP}° grid (Natural Earth 110m), one hex row per latitude band
// from ${LAT_TOP}°N down to ${LAT_BOTTOM}°. Each hex char packs 4 cells, west to east from -180°.
export const DOT_STEP = ${STEP}
export const DOT_LAT_TOP = ${LAT_TOP}
export const DOT_LAT_BOTTOM = ${LAT_BOTTOM}
export const DOT_COLS = ${cols}
export const DOT_ROWS: readonly string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
]
`
writeFileSync(new URL('../src/renderer/src/lib/worldDots.ts', import.meta.url), out)
console.log(`${rows.length} rows x ${cols} cols, ${rows.join('').length} hex chars`)
