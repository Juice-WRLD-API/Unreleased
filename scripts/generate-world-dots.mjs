// Rasterizes Natural Earth land (via world-atlas) into the compact dot grid
// that CdnWorldMap draws, and writes src/renderer/src/lib/worldDots.ts.
//
//   npm i --no-save world-atlas@2 topojson-client@3
//   node scripts/generate-world-dots.mjs
//
// Only needs re-running to change the grid step or latitude crop.
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'

const STEP = 2          // degrees per cell
const LAT_TOP = 84      // crop: nothing useful above/below these
const LAT_BOTTOM = -58

const topo = JSON.parse(readFileSync('node_modules/world-atlas/land-50m.json', 'utf8'))
const land = feature(topo, topo.objects.land)
const rawPolys = []
for (const f of land.features ?? [land]) {
  const g = f.geometry
  if (g.type === 'Polygon') rawPolys.push(g.coordinates)
  else if (g.type === 'MultiPolygon') rawPolys.push(...g.coordinates)
}

function splitRingAtAM(ring) {
  const crossIndices = []
  for (let i = 1; i < ring.length; i++) {
    if (Math.abs(ring[i][0] - ring[i - 1][0]) > 180) crossIndices.push(i)
  }
  if (crossIndices.length === 0 || crossIndices.length % 2 !== 0) return [ring]

  const crosses = crossIndices.map((ci) => {
    const [x0, y0] = ring[ci - 1], [x1, y1] = ring[ci]
    const s = x0 > 0 ? 1 : -1
    const t = (s * 180 - x0) / (x1 + s * 360 - x0)
    return { ci, lat: y0 + t * (y1 - y0), side: s }
  })

  const subs = []
  for (let k = 0; k < crosses.length; k++) {
    const from = crosses[k]
    const to = crosses[(k + 1) % crosses.length]
    const path = [[-from.side * 180, from.lat]]
    if (k < crosses.length - 1) {
      for (let i = from.ci; i < to.ci; i++) path.push(ring[i])
    } else {
      for (let i = from.ci; i < ring.length - 1; i++) path.push(ring[i])
      for (let i = 0; i < to.ci; i++) path.push(ring[i])
    }
    path.push([to.side * 180, to.lat])
    path.push(path[0])
    subs.push(path)
  }
  return subs
}

const polys = []
for (const rings of rawPolys) {
  const outerSplits = splitRingAtAM(rings[0])
  const holes = rings.slice(1)
  for (const outer of outerSplits) {
    polys.push([outer, ...holes])
  }
}

function inRing(x, y, ring) {
  let inside = false
  for (let i = 0, j = ring.length - 1; i < ring.length; j = i++) {
    const [xi, yi] = ring[i], [xj, yj] = ring[j]
    if ((yi > y) !== (yj > y) && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside
  }
  return inside
}

const onLand = (x, y) => polys.some((rings) => rings.reduce((n, r) => n + (inRing(x, y, r) ? 1 : 0), 0) % 2 === 1)

const cols = 360 / STEP
const rows = []
for (let lat = LAT_TOP - STEP / 2; lat > LAT_BOTTOM; lat -= STEP) {
  let bits = ''
  for (let c = 0; c < cols; c++) bits += onLand(-180 + (c + 0.5) * STEP, lat) ? '1' : '0'
  let hex = ''
  for (let i = 0; i < bits.length; i += 4) hex += parseInt(bits.slice(i, i + 4).padEnd(4, '0'), 2).toString(16)
  rows.push(hex)
}

const out = `// GENERATED by scripts/generate-world-dots.mjs - do not edit by hand.
// Land mask on a ${STEP}° grid (Natural Earth 50m), one hex row per latitude band
// from ${LAT_TOP}°N down to ${LAT_BOTTOM}°. Each hex char packs 4 cells, west to east from -180°.
export const DOT_STEP = ${STEP}
export const DOT_LAT_TOP = ${LAT_TOP}
export const DOT_LAT_BOTTOM = ${LAT_BOTTOM}
export const DOT_COLS = ${cols}
export const DOT_ROWS: readonly string[] = [
${rows.map((r) => `  '${r}',`).join('\n')}
]
`
writeFileSync(new URL('../src/renderer/src/lib/worldDots.ts', import.meta.url), out)
console.log(`${rows.length} rows x ${cols} cols, ${rows.join('').length} hex chars`)
