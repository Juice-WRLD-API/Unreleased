// Bakes the fullscreen visualizer's colours for the era images under the API
// site's /assets/ - the cover of every tracker song that has no art of its own.
// Those files are served with no CORS header, so the browser can't read their
// pixels at runtime and the visualizer would otherwise fall back to the accent
// colour for all of them.
//
//   node scripts/bake-era-palettes.mjs
//
// Rerun when an era image is added or changed, and commit the regenerated
// src/renderer/src/lib/eraPalettes.ts. Needs Node 22.18+ (it imports palette.ts
// directly) and the `sharp` devDependency, which only decodes and downsizes the
// images; the colour extraction itself is the app's own paletteFromPixels, so
// baked and live palettes come from the same code.

import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import sharp from 'sharp'
import { paletteFromPixels, PALETTE_SAMPLE } from '../src/renderer/src/lib/viz/palette.ts'

// Mirrors JWAPI_BASE in juicewrldApi.ts (not imported: that module needs a browser).
const SITE = 'https://juicewrldapi.com'
const OUT = fileURLToPath(new URL('../src/renderer/src/lib/eraPalettes.ts', import.meta.url))

async function decode(bytes) {
  const raw = await sharp(bytes)
    .resize(PALETTE_SAMPLE, PALETTE_SAMPLE, { fit: 'fill' })
    .ensureAlpha()
    .raw()
    .toBuffer()
  if (raw.length !== PALETTE_SAMPLE * PALETTE_SAMPLE * 4) throw new Error(`decoded ${raw.length} bytes`)
  return raw
}

const res = await fetch(`${SITE}/juicewrld/songs/?all=true`)
if (!res.ok) throw new Error(`song list: HTTP ${res.status}`)
const body = await res.json()
const songs = Array.isArray(body) ? body : body.results
const paths = [...new Set(songs.map((s) => s.image_url).filter((u) => typeof u === 'string' && u.startsWith('/assets/')))].sort()

const palettes = {}
const failed = []
const missing = []
for (const path of paths) {
  try {
    const img = await fetch(SITE + path)
    if (!img.ok) throw new Error(`HTTP ${img.status}`)
    // A path with no file behind it gets the site's HTML page with a 200, not
    // a 404. That's a broken cover on the server, not a problem to fail on.
    const type = img.headers.get('content-type') ?? ''
    if (!type.startsWith('image/')) {
      missing.push(`${path} (served as ${type || 'unknown'})`)
      continue
    }
    const pal = paletteFromPixels(await decode(Buffer.from(await img.arrayBuffer())))
    if (!pal) throw new Error('no usable pixels')
    palettes[path] = pal.map(({ r, g, b }) => ({ r: Math.round(r), g: Math.round(g), b: Math.round(b) }))
  } catch (e) {
    failed.push(`${path}: ${e.message}`)
  }
}

const rows = Object.entries(palettes).map(([path, pal]) =>
  `  '${path}': [${pal.map((c) => `{ r: ${c.r}, g: ${c.g}, b: ${c.b} }`).join(', ')}],`)
writeFileSync(OUT, `// Generated by scripts/bake-era-palettes.mjs - do not edit by hand.
//
// Visualizer colours for the era images under the API site's /assets/, which
// are served without CORS and so can't be sampled in the browser. An image
// missing from here falls back to the accent colour; rerun the script to add it.

import type { RGB } from './viz/types'

export const ERA_PALETTES: Readonly<Record<string, RGB[]>> = {
${rows.join('\n')}
}
`)

console.log(`baked ${Object.keys(palettes).length}/${paths.length} era palettes -> ${OUT}`)
if (missing.length) console.warn(`not an image on the server, skipped:\n  ${missing.join('\n  ')}`)
if (failed.length) {
  console.error(`failed:\n  ${failed.join('\n  ')}`)
  process.exit(1)
}
